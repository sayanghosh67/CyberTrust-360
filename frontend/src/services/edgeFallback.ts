// Client-side Threat Graph Engine
export function getEdgeThreatGraph(
  filterType?: string,
  search?: string,
  limit: number = 100,
  _includeDemo: boolean = false
): GraphResponse {
  const scans = getEdgeScans();
  const scams = getEdgeScams();

  const nodes: GraphNodeData[] = [];
  const edges: GraphEdgeData[] = [];
  const nodeMap = new Set<string>();

  const addNode = (node: GraphNodeData) => {
    if (!nodeMap.has(node.id)) {
      nodeMap.add(node.id);
      nodes.push(node);
    }
  };

  // Base clusters
  addNode({
    id: 'cluster-jamtara-kyc',
    type: 'tactic',
    label: 'Jamtara KYC Syndicate',
    sublabel: 'Active Cybercrime Cluster',
    risk_classification: 'Confirmed Malicious',
    risk_score: 95,
    severity: 'critical',
    report_count: 8,
    properties: { origin: 'Jharkhand / Jamtara Corridor', target_sectors: ['Banking', 'UPI'] }
  });

  addNode({
    id: 'cluster-task-scam',
    type: 'tactic',
    label: 'Southeast Asia Task Syndicate',
    sublabel: 'Telegram Investment Ring',
    risk_classification: 'High Risk',
    risk_score: 88,
    severity: 'high',
    report_count: 5,
    properties: { modus_operandi: 'YouTube / Hotel Likes', target_sectors: ['Young Jobseekers'] }
  });

  // Add scan nodes
  scans.forEach((scan) => {
    addNode({
      id: scan.id,
      type: 'url_scan',
      label: scan.hostname,
      sublabel: `URL Scan (${scan.risk_score}/100)`,
      risk_classification: scan.risk_classification,
      risk_score: scan.risk_score,
      severity: scan.risk_score >= 80 ? 'critical' : scan.risk_score >= 50 ? 'high' : 'low',
      report_count: 1,
      properties: { url: scan.url }
    });

    if (scan.risk_score >= 70) {
      edges.push({
        id: `edge-${scan.id}-cluster`,
        source: scan.id,
        target: 'cluster-jamtara-kyc',
        label: 'Shared Modus Operandi',
        relationship_type: 'INFRASTRUCTURE_LINK',
        category: 'POSSIBLE_RELATIONSHIP',
        evidence: `Domain ${scan.hostname} matches known banking phishing attack vector.`,
        source_report_ids: [scan.id],
        confidence: 'High',
        weight: 0.85,
        limitations: 'Inferred behavioral correlation'
      });
    }
  });

  // Add scam nodes
  scams.forEach((scam) => {
    addNode({
      id: scam.id,
      type: 'scam_report',
      label: scam.scam_archetype,
      sublabel: `Scam DNA (${scam.risk_score}/100)`,
      risk_classification: scam.risk_classification,
      risk_score: scam.risk_score,
      severity: scam.risk_score >= 80 ? 'critical' : 'high',
      report_count: 1,
      properties: { preview: scam.message_preview }
    });

    // Add extracted indicator nodes
    scam.extracted_indicators.forEach((ind, idx) => {
      const indId = `ind-${ind.type}-${ind.value}`;
      addNode({
        id: indId,
        type: 'indicator',
        label: ind.value,
        sublabel: ind.type.toUpperCase(),
        severity: 'high',
        report_count: 2,
        properties: { snippet: ind.context_snippet }
      });

      edges.push({
        id: `edge-${scam.id}-${idx}`,
        source: scam.id,
        target: indId,
        label: 'Extracted Threat Indicator',
        relationship_type: 'INDICATOR_EXTRACTION',
        category: 'VERIFIED_SHARED_INDICATOR',
        evidence: `Indicator ${ind.value} extracted from scam message.`,
        source_report_ids: [scam.id],
        confidence: 'High',
        weight: 1.0,
        limitations: 'Verified indicator linkage'
      });
    });
  });

  // Filter if needed
  let filteredNodes = nodes;
  if (filterType && filterType !== 'all') {
    filteredNodes = nodes.filter((n) => n.type === filterType);
  }

  if (search && search.trim()) {
    const q = search.toLowerCase().trim();
    filteredNodes = filteredNodes.filter((n) => n.label.toLowerCase().includes(q) || (n.sublabel && n.sublabel.toLowerCase().includes(q)));
  }

  const validIds = new Set(filteredNodes.map((n) => n.id));
  const filteredEdges = edges.filter((e) => validIds.has(e.source) && validIds.has(e.target));

  return {
    nodes: filteredNodes.slice(0, limit),
    edges: filteredEdges.slice(0, limit),
    total_reports_analyzed: scans.length + scams.length,
    verified_relationships_count: filteredEdges.filter((e) => e.category === 'VERIFIED_SHARED_INDICATOR').length,
    possible_relationships_count: filteredEdges.filter((e) => e.category === 'POSSIBLE_RELATIONSHIP').length,
    is_demo_data: false,
    generated_at: new Date().toISOString()
  };
}

