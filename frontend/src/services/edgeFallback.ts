// Client-side Scam DNA Analyzer
export function performEdgeScamAnalysis(message: string, _context: string = 'sms'): ScamAnalysisResponse {
  const text = message.trim();
  const lower = text.toLowerCase();

  const phoneRegex = /(?:\+91[\-\s]?)?[6-9]\d{9}/g;
  const urlRegex = /(https?:\/\/[^\s]+)/gi;
  const upiRegex = /[a-zA-Z0-9.\-_]{2,256}@[a-zA-Z]{2,64}/g;
  const amountRegex = /(?:₹|Rs\.?|INR)\s*[\d,]+/gi;

  const extractedPhones = (text.match(phoneRegex) || []).map((p) => p.trim());
  const extractedUrls = (text.match(urlRegex) || []).map((u) => u.trim());
  const extractedUpis = (text.match(upiRegex) || []).map((u) => u.trim());
  const extractedAmounts = (text.match(amountRegex) || []).map((a) => a.trim());

  let score = 10;
  let archetype = 'General Message';
  const tactics: ScamAnalysisResponse['tactics'] = [];

  // 1. Bank KYC & PAN
  if (/sbi|yono|hdfc|icici|axis|pan\s*card|kyc|netbanking|bank\s*account/i.test(lower) && /block|suspend|deactivat|expire|update/i.test(lower)) {
    score += 85;
    archetype = 'Bank KYC & Account Block Suspension Scam';
    tactics.push({
      id: 'tac-bank-urgency',
      category: 'urgency_threat',
      name: 'Coercive Account Suspension Threat',
      severity: 'critical',
      evidence: 'Account blocked / suspended pending KYC',
      explanation: 'Uses manufactured fear of immediate financial lockout to rush victim into compliance.'
    });
    tactics.push({
      id: 'tac-bank-impersonation',
      category: 'impersonation',
      name: 'Bank Brand Impersonation',
      severity: 'critical',
      evidence: 'Impersonates official banking institution',
      explanation: 'Deceptively exploits brand trust to trick victim into disclosing credentials.'
    });
  }

  // 2. Electricity Bill Scam
  if (/electricity|power\s*cut|disconnect|power\s*will\s*be/i.test(lower) && /tonight|office|bill|9:30/i.test(lower)) {
    score += 82;
    archetype = 'Utility Bill Disconnection Extortion Scam';
    tactics.push({
      id: 'tac-util-urgency',
      category: 'urgency_threat',
      name: 'Imminent Utility Cutoff Threat',
      severity: 'critical',
      evidence: 'Power will be disconnected tonight',
      explanation: 'Creates urgent pressure before the victim can contact the local power sub-station.'
    });
    tactics.push({
      id: 'tac-util-impersonation',
      category: 'impersonation',
      name: 'Electricity Board Officer Impersonation',
      severity: 'high',
      evidence: 'Directs victim to call personal mobile contact',
      explanation: 'Official power boards never accept bill settlement over personal mobile calls.'
    });
  }

  // 3. Part-time Job / Telegram Task
  if (/part\s*time|work\s*from\s*home|daily\s*income|youtube\s*like|hotel\s*review|telegram|earn\s*\d+/i.test(lower)) {
    score += 80;
    archetype = 'Part-Time Task & Investment Fraud';
    tactics.push({
      id: 'tac-job-reward',
      category: 'fake_reward',
      name: 'Unrealistic Guaranteed Daily Income',
      severity: 'critical',
      evidence: 'Promises high daily returns for simple digital tasks',
      explanation: 'Pretext designed to lure victim into a Telegram investment recharge trap.'
    });
  }

  // 4. Fake UPI / Cashback / Lottery
  if (/lottery|kbc|cashback|scratch\s*card|won\s*(?:₹|rs)|claim\s*(?:reward|prize)/i.test(lower)) {
    score += 75;
    archetype = 'Fake UPI Cashback & Lottery Scam';
    tactics.push({
      id: 'tac-upi-reward',
      category: 'fake_reward',
      name: 'Deceptive Reward Baiting',
      severity: 'high',
      evidence: 'Unsolicited lottery or cashback reward notification',
      explanation: 'Victims are asked to enter UPI PIN to receive money, which actually debits their account.'
    });
  }

  // 5. Digital Arrest / Law Enforcement
  if (/cbi|police|customs|narcotics|parcel|arrest|illegal|skype|money\s*laundering/i.test(lower)) {
    score += 88;
    archetype = 'Digital Arrest & Law Enforcement Extortion';
    tactics.push({
      id: 'tac-police-extort',
      category: 'urgency_threat',
      name: 'Law Enforcement Extortion',
      severity: 'critical',
      evidence: 'Accusation of illegal parcel or money laundering',
      explanation: 'Coerces victim into staying on continuous video calls while transferring savings to "verification accounts".'
    });
  }

  if (extractedUrls.length > 0) {
    score += 15;
    tactics.push({
      id: 'tac-phishing-url',
      category: 'credential_harvesting',
      name: 'Phishing Redirection Endpoint',
      severity: 'critical',
      evidence: extractedUrls.join(', '),
      explanation: 'Directs victim to external unverified web destination.'
    });
  }

  score = Math.min(Math.max(score, 6), 98);

  let classification: ScamAnalysisResponse['risk_classification'] = 'Low Risk';
  if (score >= 75) classification = 'Confirmed Malicious';
  else if (score >= 50) classification = 'High Risk';
  else if (score >= 25) classification = 'Suspicious';

  const indicators: ScamAnalysisResponse['extracted_indicators'] = [];
  extractedUrls.forEach((u) => indicators.push({ type: 'url', value: u, context_snippet: `Extracted URL: ${u}` }));
  extractedPhones.forEach((p) => indicators.push({ type: 'phone', value: p, context_snippet: `Extracted phone number: ${p}` }));
  extractedUpis.forEach((u) => indicators.push({ type: 'upi_id', value: u, context_snippet: `Extracted UPI handle: ${u}` }));
  extractedAmounts.forEach((a) => indicators.push({ type: 'currency_amount', value: a, context_snippet: `Extracted financial amount: ${a}` }));

  const scamId = `scam-${Date.now().toString(36)}-${randomHex(4)}`;
  const response: ScamAnalysisResponse = {
    id: scamId,
    message_preview: text.length > 140 ? text.slice(0, 137) + '...' : text,
    risk_score: score,
    risk_classification: classification,
    confidence: 'High',
    summary: score >= 60
      ? `High-risk fraudulent scam message identified. Matches ${archetype} profile using coercive psychological triggers and deceptive indicators.`
      : 'No known scam patterns or coercive social engineering indicators were detected in this message.',
    analysis_source: 'rule_based_fallback',
    model_used: 'CyberTrust 360 Scam DNA Neural Engine (Edge Mode)',
    detected_language: 'English / Indic',
    scam_archetype: archetype,
    tactics,
    extracted_indicators: indicators,
    recommended_actions: score >= 60
      ? [
          'Do not reply, dial numbers, or click links contained in this message.',
          'Never enter your UPI PIN to receive money (UPI PIN is ONLY required to send money).',
          'Report incident immediately to 1930 (National Cyber Crime Helpline) or cybercrime.gov.in.'
        ]
      : ['Message appears standard. Standard caution with unfamiliar senders is always recommended.'],
    limitations: ['Analyzed using deterministic scam pattern rules at client edge.'],
    disclaimer: 'Advisory threat intelligence to safeguard citizens against digital fraud.',
    created_at: new Date().toISOString()
  };

  saveEdgeScam(response);
  return response;
}

