export async function performEdgeBlockchainTamper(reportId: string): Promise<BlockchainVerification> {
  try {
    const raw = localStorage.getItem(STORAGE_TAMPERED);
    const list: string[] = raw ? JSON.parse(raw) : [];
    if (!list.includes(reportId)) {
      list.push(reportId);
      localStorage.setItem(STORAGE_TAMPERED, JSON.stringify(list));
    }
  } catch {
    // Ignore error
  }
  return performEdgeBlockchainVerify(reportId);
}

