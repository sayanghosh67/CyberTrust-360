export function getEdgeScans(): ScanResponse[] {
  try {
    const raw = localStorage.getItem(STORAGE_SCANS);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch {
    // Ignore storage errors
  }
  return SEED_SCANS;
}

export function saveEdgeScan(scan: ScanResponse): void {
  try {
    const existing = getEdgeScans().filter((s) => s.id !== scan.id);
    const updated = [scan, ...existing].slice(0, 30);
    localStorage.setItem(STORAGE_SCANS, JSON.stringify(updated));
  } catch {
    // Ignore storage errors
  }
}

